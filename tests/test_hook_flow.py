"""End-to-end: drive the hooks with the JSON Claude Code sends, in a throwaway git repo."""

import json
import os
import time

from conftest import decision, git, hook

PLAN = """# Add subtract function

## Goal
app.py gains subtract().

## Approach
Mirror add().

## Rejected alternative
A generic op() dispatcher; overkill.

## Files
- app.py: new function

## Tests
- none yet

## Steps
1. write it
"""

REPORT = """# Add subtract function

## What changed
app.py now has subtract(a, b) next to add().

## Why
Callers needed it. A generic dispatcher was rejected as premature.

## Concept (pure functions)
subtract() depends only on its inputs, so it is trivial to test. See app.py line 5.
"""


def state(root):
    with open(os.path.join(root, ".cock-cage", "state.json")) as fh:
        return json.load(fh)


def rp_path(root):
    return os.path.join(root, ".cock-cage", "reports.md")


def wait_baseline(root, limit=60):
    end = time.time() + limit
    while time.time() < end:
        if state(root).get("baseline_status") in ("ready", "contaminated", "none"):
            return state(root)["baseline_status"]
        time.sleep(0.3)
    raise AssertionError("baseline never finished")


def setup(root):
    import subprocess, sys
    from conftest import CC
    r = subprocess.run([sys.executable, CC, "init", "--no-tools", "--no-baseline"], cwd=root, capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


def test_full_task_cycle(repo):
    root = str(repo)
    setup(root)
    out = hook(root, "session-start", {"source": "startup"})
    ctx = out["hookSpecificOutput"]["additionalContext"]
    assert "cock-cage is active" in ctx and "def add(a, b)" in ctx
    assert os.access(os.path.join(root, ".cock-cage", "bin", "cockcage"), os.X_OK)
    assert wait_baseline(root) == "ready"

    # 1. editing before a plan is blocked; writing the plan is fine
    assert decision(hook(root, "pre-tool", {"tool_name": "Write", "tool_input": {"file_path": os.path.join(root, "app.py")}})) == "deny"
    plan_path = os.path.join(root, ".cock-cage", "plan.md")
    assert hook(root, "pre-tool", {"tool_name": "Write", "tool_input": {"file_path": plan_path}}) is None
    open(plan_path, "w").write(PLAN)
    hook(root, "post-tool", {"tool_name": "Write", "tool_input": {"file_path": plan_path}})
    assert state(root)["task"]["phase"] == "planning"

    # 2. a hedged reply does not approve; a clear one does, and moves work off main
    hook(root, "user-prompt", {"prompt": "ok but change the name"})
    assert state(root)["task"]["phase"] == "planning"
    out = hook(root, "user-prompt", {"prompt": "approve"})
    assert "approved" in out["hookSpecificOutput"]["additionalContext"]
    assert state(root)["task"]["phase"] == "approved"
    assert git(root, "branch", "--show-current").stdout.strip() == "cc/add-subtract-function"

    # 3. edits now pass and are tracked
    app = os.path.join(root, "app.py")
    assert hook(root, "pre-tool", {"tool_name": "Edit", "tool_input": {"file_path": app}}) is None
    with open(app, "a") as fh:
        fh.write("\n\ndef subtract(a, b):\n    return a - b\n")
    hook(root, "post-tool", {"tool_name": "Edit", "tool_input": {"file_path": app}})
    assert state(root)["task"]["touched"] == ["app.py"]

    # 4. turn ends without a report are work in progress: nothing blocks, the user sees the status
    out = hook(root, "stop", {"last_assistant_message": "Want me to add tests too?"})
    assert "decision" not in out and "in progress" in out["systemMessage"]
    # an incomplete report blocks until fixed
    open(os.path.join(root, ".cock-cage", "report-draft.md"), "w").write("# Add subtract function\n\n## Why\nx\n")
    out = hook(root, "stop", {"last_assistant_message": "Done."})
    assert out["decision"] == "block" and "What Changed" in out["reason"]

    # 5. with a report: ledger entry, checkpoint commit, plan archived, task reset
    open(os.path.join(root, ".cock-cage", "report-draft.md"), "w").write(REPORT)
    out = hook(root, "stop", {"last_assistant_message": "Done.", "stop_hook_active": True})
    assert "report #1 logged" in out["systemMessage"], out
    assert "commit" in out["systemMessage"] and "merged into main" in out["systemMessage"]
    # finished work is merged into main and the task branch is gone
    assert git(root, "branch", "--show-current").stdout.strip() == "main"
    assert "cc/add-subtract-function" not in git(root, "branch").stdout
    log = git(root, "log", "-1", "--pretty=%s%n%b").stdout
    assert log.startswith("feat: Add subtract function") and "Report #1" in log
    assert git(root, "show", "--stat", "HEAD").stdout.count("app.py") == 1
    ledger_text = open(os.path.join(root, ".cock-cage", "reports.md")).read()
    assert "### Concept (pure functions)" in ledger_text and "### Evidence (generated by cock-cage)" in ledger_text
    assert "merged: main" in ledger_text
    assert "app.py (+4" in ledger_text
    assert not os.path.exists(plan_path)
    assert os.listdir(os.path.join(root, ".cock-cage", "plans"))
    st = state(root)
    assert st["task"]["phase"] == "idle" and st["baseline_status"] == "ready"
    # ledger, state and plans are never committed; only config.json is shared
    tracked = git(root, "ls-files", ".cock-cage").stdout.split()
    assert set(tracked) == {".cock-cage/.gitignore", ".cock-cage/config.json"}
    assert "reports.md" in git(root, "status", "--porcelain", "--ignored").stdout or os.path.exists(rp_path(root))

    # 6. Claude cannot touch the ledger; tampering is reported at the next session start
    assert decision(hook(root, "pre-tool", {"tool_name": "Edit", "tool_input": {"file_path": os.path.join(root, ".cock-cage", "reports.md")}})) == "deny"
    rp = os.path.join(root, ".cock-cage", "reports.md")
    text = open(rp).read()
    assert "subtract" in text
    open(rp, "w").write(text.replace("subtract", "minus"))
    out = hook(root, "session-start", {"source": "resume"})
    assert "failed verification" in out["systemMessage"]


def test_quick_mode_and_give_up(repo):
    root = str(repo)
    setup(root)
    hook(root, "session-start", {"source": "startup"})
    wait_baseline(root)
    hook(root, "user-prompt", {"prompt": "quick: fix typo in add"})
    st = state(root)
    assert st["task"]["phase"] == "quick" and st["task"]["title"] == "fix typo in add"
    app = os.path.join(root, "app.py")
    assert hook(root, "pre-tool", {"tool_name": "Edit", "tool_input": {"file_path": app}}) is None
    with open(app, "a") as fh:
        fh.write("\n# note\n")
    hook(root, "post-tool", {"tool_name": "Edit", "tool_input": {"file_path": app}})
    assert git(root, "branch", "--show-current").stdout.strip() == "cc/fix-typo-in-add"
    open(os.path.join(root, ".cock-cage", "report-draft.md"), "w").write("# fix typo in add\n\n## Why\nx\n")
    for i in range(3):
        out = hook(root, "stop", {"last_assistant_message": "Done.", "stop_hook_active": i > 0})
        assert out["decision"] == "block"
    out = hook(root, "stop", {"last_assistant_message": "Done.", "stop_hook_active": True})
    assert "report #1 logged" in out["systemMessage"]
    text = open(os.path.join(root, ".cock-cage", "reports.md")).read()
    assert "[unresolved]" in text and "UNRESOLVED report" in text
    assert git(root, "branch", "--show-current").stdout.strip() == "cc/fix-typo-in-add", "unresolved work is not merged"


def test_hooks_do_nothing_outside_initialised_projects(tmp_path):
    root = str(tmp_path)
    assert hook(root, "pre-tool", {"tool_name": "Write", "tool_input": {"file_path": os.path.join(root, "x.py")}}) is None
    assert hook(root, "stop", {}) is None


def test_broken_payload_fails_open(repo):
    import subprocess, sys
    from conftest import CC
    proc = subprocess.run([sys.executable, CC, "hook", "pre-tool"], input="not json", capture_output=True, text=True,
                          cwd=str(repo), env=dict(os.environ, CLAUDE_PROJECT_DIR=str(repo)))
    assert proc.returncode == 0 and proc.stdout == ""
