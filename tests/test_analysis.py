import textwrap

from cockcage import checks, codemap, config, dupes, report, versioning

ORDERS = textwrap.dedent('''
    """Order handling."""


    class Order:
        """An order."""

        def __init__(self, items: list, *, currency: str = "GBP") -> None:
            self.items = items

        def total(self) -> float:
            return sum(i["price"] * i["qty"] for i in self.items)


    async def fetch(url: str, retries=3) -> bytes:
        """Fetch a URL with retries."""
        return b""
''')


def test_codemap_lists_symbols_with_signatures(tmp_path):
    (tmp_path / "orders.py").write_text(ORDERS)
    (tmp_path / "tests").mkdir()
    (tmp_path / "tests" / "test_orders.py").write_text("def test_a():\n    pass\n\ndef test_b():\n    pass\n")
    (tmp_path / ".venv").mkdir()
    (tmp_path / ".venv" / "junk.py").write_text("def nope(): pass\n")
    info = codemap.build(str(tmp_path))
    text = info["text"]
    assert "class Order" in text and "def total(self) -> float" in text
    assert "async def fetch(url: str, retries=…) -> bytes" in text and "Fetch a URL" in text
    assert "def __init__(self, items: list, *, currency=…) -> None" in text
    assert "2 tests" in text and "nope" not in text
    assert info["files"] == 2


def test_codemap_index_when_large(tmp_path):
    for i in range(30):
        (tmp_path / ("m%02d.py" % i)).write_text(ORDERS)
    codemap.build(str(tmp_path))
    snippet = codemap.context_snippet(str(tmp_path), 800)
    assert snippet.startswith("# Code map (index")
    assert len(snippet) < 1200


DUP_A = textwrap.dedent('''
    def load_prices(path):
        rows = []
        with open(path) as fh:
            for line in fh:
                parts = line.strip().split(",")
                if len(parts) != 3:
                    continue
                rows.append({"date": parts[0], "price": float(parts[1]), "qty": int(parts[2])})
        return rows
''')
DUP_B_RENAMED = DUP_A.replace("load_prices", "read_trades").replace("rows", "out").replace("fh", "f")


def test_duplicates_copy_paste_and_renamed(tmp_path):
    (tmp_path / "a.py").write_text(DUP_A)
    (tmp_path / "b.py").write_text(DUP_A.replace("load_prices", "load_prices_again"))
    (tmp_path / "c.py").write_text(DUP_B_RENAMED)
    groups = dupes.find(str(tmp_path), [str(tmp_path / f) for f in ("a.py", "b.py", "c.py")])
    kinds = {g["kind"] for g in groups}
    assert "copy-paste" in kinds and "same-shape functions" in kinds
    shape = [g for g in groups if g["kind"] == "same-shape functions"][0]
    assert {"a.py", "b.py", "c.py"} == {loc[0] for loc in shape["locations"]}
    # focus filter
    assert dupes.find(str(tmp_path), [str(tmp_path / "a.py")], focus=["zzz.py"]) == []


def test_report_validation_and_compose():
    good = textwrap.dedent("""
        # Add retry logic

        ## What changed
        fetch() retries.

        ## Why
        The API drops requests. Rejected tenacity as overkill.

        ## Concept (exponential backoff)
        Each retry waits twice as long. See client.py line 42.
    """)
    assert report.validate(good, 220) == []
    assert any("Missing" in p for p in report.validate("## What changed\nx\n", 220))
    assert any("Trim" in p for p in report.validate(good + "\nword" * 300, 220))
    assert any("unfilled" in p for p in report.validate(report.TEMPLATE, 220))
    title, body = report.compose(good, "fallback", {"branch": "cc/x"}, ["pytest: 3 passed"], {"duplicates": ["a"]}, {})
    assert title == "Add retry logic"
    assert "### Concept (exponential backoff)" in body and "### Evidence (generated by cock-cage)" in body
    assert "- duplicates: a" in body and "branch: cc/x" in body


def test_compare_only_new_problems_count():
    base = {"lint": {"ran": True, "items": ["a.py:E1:x"]}, "tests": {"ran": True, "failing": ["t::old"]},
            "complexity": {"ran": True, "items": []}, "coverage": {"ran": True, "files": {"a.py": 90.0}}}
    cur = {"lint": {"ran": True, "items": ["a.py:E1:x", "b.py:F401:y"]}, "tests": {"ran": True, "failing": ["t::old", "t::new"]},
           "complexity": {"ran": True, "items": ["a.py:too complex", "z.py:too complex"]},
           "coverage": {"ran": True, "files": {"a.py": 70.0, "b.py": 10.0}}}
    new = checks.compare(base, cur, ["a.py", "b.py"], True)
    assert new["lint"] == ["b.py:F401:y"]
    assert new["tests"] == ["t::new"]
    assert new["complexity"] == ["a.py:too complex"]
    assert len(new["coverage"]) == 2
    assert checks.compare(base, cur, [], False)["tests"] == ["t::old", "t::new"]


def test_config_defaults_and_levels(tmp_path):
    root = str(tmp_path)
    config.write_default(root, {"levels": {"tests": "warn", "bogus": "x"}})
    cfg = config.load(root)
    assert config.level(cfg, "tests") == "warn"
    assert config.level(cfg, "lint") == "block"
    assert config.level(cfg, "bogus") == "warn"
    raw, notes = config.migrate({"schema": 99})
    assert any("newer" in n for n in notes)


def test_semver_and_pyproject(tmp_path):
    assert versioning.bump("1.2.3", "patch") == "1.2.4"
    assert versioning.bump("1.2.3", "minor") == "1.3.0"
    assert versioning.bump("1.2.3", "major") == "2.0.0"
    (tmp_path / "pyproject.toml").write_text('[tool.x]\nversion = "9.9.9"\n\n[project]\nname = "p"\nversion = "0.1.0"\n\n[tool.y]\nversion="1"\n')
    assert versioning.read_project_version(str(tmp_path)) == "0.1.0"
    versioning.write_project_version(str(tmp_path), "0.2.0")
    text = (tmp_path / "pyproject.toml").read_text()
    assert 'version = "0.2.0"' in text and 'version = "9.9.9"' in text and 'version="1"' in text
