"""Report drafts written by Claude, validated and enriched with evidence by the Stop hook."""

from __future__ import annotations

import re
from typing import Dict, List, Optional, Tuple

from . import util

REQUIRED = ("what changed", "why", "concept")
OPTIONAL = ("watch out",)
_HEAD = re.compile(r"^\s{0,3}(#{1,6}\s*)?(?P<name>what changed|why|concept\b[^\n]*|watch out)\s*:?\s*$", re.I)
_TITLE = re.compile(r"^\s{0,3}#\s+(?P<t>.+?)\s*$")

TEMPLATE = """# <one-line task title>

## What changed
<2-4 lines: files and functions touched, in plain words>

## Why
<the decision, and the main alternative you rejected>

## Concept (<name of the idea>)
<2-3 sentences teaching the one idea worth learning here, pointing to file:line>

## Watch out
<only if there is a risk, a trade-off or an open question; otherwise delete this section>
"""


def draft_path(root: str) -> str:
    return util.cc_path(root, "report-draft.md")


def parse(text: str) -> Tuple[str, Dict[str, str]]:
    title = ""
    sections: Dict[str, List[str]] = {}
    current: Optional[str] = None
    for line in text.splitlines():
        m = _HEAD.match(line)
        if m:
            name = m.group("name").strip()
            key = name.lower()
            key = "concept" if key.startswith("concept") else key
            current = key
            sections.setdefault(current, [])
            if key == "concept":
                sections.setdefault("_concept_heading", []).append(name)
            continue
        t = _TITLE.match(line)
        if t and not title and current is None:
            title = t.group("t").strip()
            continue
        if current is not None:
            sections[current].append(line)
    return title, {k: "\n".join(v).strip() for k, v in sections.items()}


def words(s: str) -> int:
    return len(re.findall(r"\b\w+\b", s))


def validate(text: str, max_words: int) -> List[str]:
    if not text.strip():
        return ["The report draft is empty."]
    _, secs = parse(text)
    problems = []
    for name in REQUIRED:
        body = secs.get(name, "")
        if not body or "<" in body and ">" in body and body.strip().startswith("<"):
            problems.append("Missing or unfilled section: %s" % name.title())
    total = sum(words(v) for k, v in secs.items() if not k.startswith("_"))
    if total > max_words:
        problems.append("The report is %d words. Trim it to %d or fewer; detail belongs in the code and commit." % (total, max_words))
    return problems


def compose(text: str, fallback_title: str, meta: Dict[str, str], evidence: List[str],
            warnings: Dict[str, List[str]], noted: Dict[str, List[str]]) -> Tuple[str, str]:
    """Return (title, ledger entry body)."""
    title, secs = parse(text)
    title = title or fallback_title or "Untitled task"
    concept_head = (secs.get("_concept_heading") or "Concept").split("\n")[0]
    out: List[str] = []
    meta_line = " · ".join("%s: %s" % (k, v) for k, v in meta.items() if v)
    if meta_line:
        out.append(meta_line)
        out.append("")
    out.append("### What changed\n%s\n" % secs.get("what changed", "").strip())
    out.append("### Why\n%s\n" % secs.get("why", "").strip())
    out.append("### %s\n%s\n" % (concept_head[0].upper() + concept_head[1:], secs.get("concept", "").strip()))
    if secs.get("watch out"):
        out.append("### Watch out\n%s\n" % secs["watch out"].strip())
    out.append("### Evidence (generated by cock-cage)")
    out.extend("- %s" % e for e in evidence)
    out.append("")
    if warnings:
        out.append("### Warnings")
        for k, items in warnings.items():
            for i in items[:8]:
                out.append("- %s: %s" % (k.replace("_", " "), i))
            if len(items) > 8:
                out.append("- %s: … %d more" % (k.replace("_", " "), len(items) - 8))
        out.append("")
    if noted:
        out.append("### Noted")
        for k, items in noted.items():
            out.append("- %s: %s" % (k.replace("_", " "), "; ".join(items[:5]) + (" …" if len(items) > 5 else "")))
        out.append("")
    return title, "\n".join(out).rstrip() + "\n"
